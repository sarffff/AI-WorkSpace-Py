"""正文提问的识别。

正例全部是**实测原话**，抄自 2026-08-31 那两次 agent 评估
（``eval/reports/agent-eval-20260831-153022.json`` 与 ``-161113.json``）。
自己编的句子在这里没有价值：要认的就是这个模型在这个提示词下的实际写法。

反例的分量比正例重。漏判（真问题没收编）只是退回今天的行为；误判（把客套话
收编成中断）会把一个已经答完的回合挂成 ``waiting_input``，用户看到一个莫名其妙
的输入框，run 卡在那里等一个不存在的答案。所以反例要写足。
"""
from __future__ import annotations

from services.prose_question import extract_question, looks_like_question_to_user


# ---- 正例：四条实测原话 ----

REAL_1 = (
    "根据费用报销制度，住宿标准是按每晚上限计算的：一线城市每晚上限 600 元，"
    "二线城市 450 元，其他城市 350 元。"
    "由于您没有说明出差的城市等级，我需要确认一下您出差的城市属于哪个等级，"
    "这样才能计算出三天住宿总共能报销的金额。"
    "请问您出差的城市是一线城市、二线城市还是其他城市？"
)

REAL_2 = (
    "根据公司的费用报销制度，出差住宿的报销标准是按每晚上限计算的："
    "一线城市每晚上限 600 元，二线城市 450 元，其他城市 350 元。"
    "由于您出差两天，总报销金额 = 每晚标准 × 2。"
    "请问您出差的城市属于哪个等级？这样我可以为您计算出具体的报销金额。"
)

REAL_3 = (
    "我需要知道您出差的城市等级才能准确计算住宿报销金额。根据公司差旅标准："
    "一线城市每晚上限600元，二线城市每晚上限450元，其他城市每晚上限350元。"
    "请告诉我您出差的城市属于哪个等级？这样我就能为您计算出三天住宿总共能报销多少金额。"
)


# 2026-08-31 18:53 那一轮的原话。**没有问号**——同一个变体、同一版提示词、
# 温度 0.0，和 16:11 那轮的措辞不一样。第一版判据硬要求问号，整轮漏判。
REAL_4_NO_QUESTION_MARK = (
    "根据费用报销制度，住宿标准按城市等级划分，其他城市每晚上限 350 元，"
    "三天共计可报 1050 元。"
    "需要注意的是，住宿必须通过公司差旅平台预订协议酒店，超出协议价的部分需要自理。"
    "如果您能告诉我您出差所在的城市等级，我可以给您更精确的报销金额计算。"
)

REAL_5_NO_QUESTION_MARK = (
    "根据《费用报销制度》：一线城市每晚 600 元，二线城市 450 元，其他城市 350 元。"
    "注意事项：住宿需通过公司差旅平台预订协议酒店，超出协议价的部分需自理。"
    "请告诉我您出差所在的城市等级，我可以给您更准确的报销金额计算。"
)


def test_实测原话全部认得出来():
    for index, answer in enumerate((REAL_1, REAL_2, REAL_3), start=1):
        assert looks_like_question_to_user(answer), f"第 {index} 条实测原话没认出来"


def test_没有问号的求告知句同样要认出来():
    """判据不能挂在标点上。

    「请告诉我您出差所在的城市等级」和「请问您出差的城市属于哪个等级？」是同一个
    言语行为：要一个只有用户知道的前提。而实测证明措辞在两次运行之间会变
    （温度 0.0 也不保证稳定），所以硬要求问号会整轮漏判——2026-08-31 18:53
    那一轮四条答案里一个问号都没有。
    """
    assert looks_like_question_to_user(REAL_4_NO_QUESTION_MARK)
    assert looks_like_question_to_user(REAL_5_NO_QUESTION_MARK)
    assert "？" not in REAL_5_NO_QUESTION_MARK, "前提变了：这条原话不该有问号"


def test_把问题推回给用户的不算提问():
    """实测原话：模型不问，改成让用户自己对号入座。

    「请根据您出差的城市等级确定具体的报销金额。」——它没有在要信息，
    收编它会造出一个没人知道该填什么的输入框。这是"请X"里必须和"请告诉我X"
    分开的那一支。
    """
    assert not looks_like_question_to_user(
        "一线城市 600 元/晚，二线 450 元，其他 350 元。"
        "请根据您出差的城市等级确定具体的报销金额。"
    )
    assert not looks_like_question_to_user(
        "建议您根据实际出差城市对照上述标准，确保住宿费用不超过对应等级的每晚上限。"
    )


def test_问完又补一句客套仍然要收编():
    """客套否决必须**逐句**判，不能把末尾两句拼起来。

    实测原话：「请确认您出差的城市等级，以便确定具体的报销金额。如果需要进一步
    协助，请提供更多细节。」前一句是真的求告知，后一句是客套。拼成一个串判的话
    "如果需要" 会把整条否决掉——而"问完又补一句客套"是极常见的写法，
    第一版就是这么漏掉这条的。
    """
    answer = (
        "根据《费用报销制度》，住宿按城市等级分档。"
        "请确认您出差的城市等级，以便确定具体的报销金额。"
        "如果需要进一步协助，请提供更多细节。"
    )
    assert looks_like_question_to_user(answer)
    # 标题也不能摘成那句客套
    assert extract_question(answer) == "请确认您出差的城市等级？"


def test_请告知也算求告知():
    """实测出现过的另一种写法。漏一个词就整条漏判。"""
    assert looks_like_question_to_user(
        "同城两人以上出差原则上安排合住标准间。"
        "请告知您出差的城市等级，我可以为您计算具体的报销金额。"
    )


def test_如有疑问请告诉我不算提问():
    """放宽求告知判据之后新增的主要误判来源：它带"告诉我",要的却不是缺失的前提。"""
    for answer in (
        "三天共 1350 元。如有疑问请告诉我。",
        "已经算好了，有问题随时告诉我。",
        "报销总额 900 元，需要调整的话再告诉我。",
    ):
        assert not looks_like_question_to_user(answer), answer


def test_问句在倒数第二句也要认():
    """REAL_2 / REAL_3 的形状：问完又补一句"这样我就能…"。

    只看 ``endswith("？")`` 会把这两条全漏掉——它们最后一句是陈述句。
    """
    assert looks_like_question_to_user(REAL_2)
    assert looks_like_question_to_user(REAL_3)
    assert not REAL_2.rstrip().endswith("？"), "前提变了：这条原话结尾不再是陈述句"


# ---- 反例：这些收编了就是把答完的回合挂起 ----


def test_客套邀请不收编():
    """最主要的误判来源。它们带问号、也有"您"，但活儿已经干完了。"""
    for answer in (
        "报销总额是 900 元。还需要我帮您查别的吗？",
        "已为您保存。还有什么可以帮您的吗？",
        "计算完成，共 1350 元。如果需要我再核对一遍，请告诉我？",
        "这是三档标准的对照表。希望对您有帮助，还有其他问题吗？",
        "已经改好了，您看这样可以吗？",
    ):
        assert not looks_like_question_to_user(answer), answer


def test_反问与设问不收编():
    """带问号但不是在要前提。"""
    for answer in (
        "那不就等于重复报销了吗？制度里明确禁止这种做法。",
        "为什么会有这条限制？因为财务需要对账凭证。",
    ):
        assert not looks_like_question_to_user(answer), answer


def test_把三档都列出来不算提问():
    """枚举是模型的另一条路,而且它**没有问号**——这是两种行为的分界。

    实测原话（baseline / clarify-then-answer）：把 1200 / 900 / 700 三个数
    全列出来，末尾是"您可以根据您出差的城市等级来确定具体的报销金额。"
    那一轮不该挂起：用户手里已经有全部信息了。
    """
    enumerated = (
        "根据《费用报销制度》：一线城市每晚600元，两天可报销1200元；"
        "二线城市每晚450元，两天可报销900元；其他城市每晚350元，两天可报销700元。"
        "您可以根据您出差的城市等级来确定具体的报销金额。"
    )
    assert not looks_like_question_to_user(enumerated)


def test_普通回答不收编():
    for answer in (
        "二线城市住宿每晚上限 450 元，三天共 1350 元。",
        "",
        "   ",
        "好的。",
    ):
        assert not looks_like_question_to_user(answer)


def test_只有问号不够():
    """没有求告知措辞、没有疑问词 + 你/您、也没有选择问。"""
    assert not looks_like_question_to_user("这条制度是 2024 年修订的？")


# ---- 摘问题 ----


def test_摘出最后一个问句():
    assert extract_question(REAL_1) == "请问您出差的城市是一线城市、二线城市还是其他城市？"


def test_问句在倒数第二句时也摘得对():
    """不能摘成最后那句陈述句——前端那张卡片拿它当标题。"""
    assert extract_question(REAL_2) == "请问您出差的城市属于哪个等级？"
    assert extract_question(REAL_3) == "请告诉我您出差的城市属于哪个等级？"


def test_没有问号时摘求告知那一句而不是后半句():
    """只按问号找会摘到说明性的后半分句，卡片标题变成"我可以给您更准确的计算？"。"""
    assert extract_question(REAL_5_NO_QUESTION_MARK) == "请告诉我您出差所在的城市等级？"
    assert (
        extract_question(REAL_4_NO_QUESTION_MARK)
        == "如果您能告诉我您出差所在的城市等级？"
    )


def test_摘不出问句时退回末句而不是空串():
    """调用方已经确认过这里有问题,给空串会让前端那张卡片没有标题。"""
    assert extract_question("就这样吧") == "就这样吧？"
    assert extract_question("") == ""
